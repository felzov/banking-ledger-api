"""The id of the request being served (ADR 0017).

Set by the API's request middleware, read by the log formatter and the audit trail. A context
variable, so it follows the request through every await and into asyncio.to_thread (the Argon2
worker threads), and uvicorn's one task per request keeps requests apart. Outside a request
(startup, the CLI, a service called directly by a test) there is none.

Always generated by the server, never taken from the client: a client-chosen id could make
unrelated requests look related in the logs and the audit trail.
"""

import uuid
from contextvars import ContextVar, Token

_request_id: ContextVar[str | None] = ContextVar("request_id", default=None)


def new_request_id() -> str:
    # UUIDv7: unique, and sortable by when the request arrived.
    return str(uuid.uuid7())


def current_request_id() -> str | None:
    return _request_id.get()


def bind_request_id(request_id: str) -> Token[str | None]:
    return _request_id.set(request_id)


def unbind_request_id(token: Token[str | None]) -> None:
    _request_id.reset(token)
